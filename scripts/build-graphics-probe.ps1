[CmdletBinding()]
param(
    [string]$DevkitPro = "C:\devkitPro",
    [string]$Workspace = (Join-Path $env:LOCALAPPDATA "Temp\opencode\castleminerz-deps")
)

$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot
$source = Join-Path $repo 'runtime-probe\graphics'
$fna3d = Join-Path $Workspace 'FNA3D'
$stage = Join-Path $Workspace 'cmz-graphics-probe-stage'
$stageMarker = Join-Path $stage '.cmz-graphics-probe-stage'
$bash = Join-Path $DevkitPro 'msys2\usr\bin\bash.exe'

foreach ($required in @(
    (Join-Path $source 'Makefile'),
    (Join-Path $source 'source\main.c'),
    (Join-Path $fna3d 'build-switch\libFNA3D.a'),
    (Join-Path $fna3d 'build-switch\libmojoshader.a'),
    (Join-Path $DevkitPro 'portlibs\switch\lib\libSDL2.a'),
    (Join-Path $DevkitPro 'portlibs\switch\lib\libEGL.a'),
    $bash
)) {
    if (-not (Test-Path -LiteralPath $required -PathType Leaf)) {
        throw "Missing graphics probe prerequisite: $required. Run setup-dependencies.ps1 and build-native-dependencies.ps1."
    }
}

if (Test-Path -LiteralPath $stage) {
    if (-not (Test-Path -LiteralPath $stageMarker -PathType Leaf)) {
        throw "Refusing to replace unrecognized staging directory: $stage"
    }
    Remove-Item -LiteralPath $stage -Recurse -Force
}
New-Item -ItemType Directory -Path $stage | Out-Null
[IO.File]::WriteAllText($stageMarker, "Generated by build-graphics-probe.ps1`n")

Copy-Item -LiteralPath (Join-Path $source 'Makefile') -Destination $stage -Force
New-Item -ItemType Directory -Force -Path (Join-Path $stage 'source') | Out-Null
Copy-Item -LiteralPath (Join-Path $source 'source\main.c') `
    -Destination (Join-Path $stage 'source\main.c') -Force

function ConvertTo-MsysPath {
    param([Parameter(Mandatory)][string]$Path)

    $result = [IO.Path]::GetFullPath($Path).Replace('\', '/')
    if ($result -match '^([A-Za-z]):/(.*)$') {
        return "/$($Matches[1].ToLower())/$($Matches[2])"
    }
    return $result
}

$msysDevkit = ConvertTo-MsysPath $DevkitPro
$msysStage = ConvertTo-MsysPath $stage
$msysFna3d = ConvertTo-MsysPath $fna3d
$command = "set -e; " +
    "export DEVKITPRO='$msysDevkit'; " +
    "export DEVKITA64='$msysDevkit/devkitA64'; " +
    "export PORTLIBS='$msysDevkit/portlibs/switch'; " +
    "export PATH='$msysDevkit/tools/bin:$msysDevkit/devkitA64/bin:/usr/bin:`$PATH'; " +
    "export FNA3D_ROOT='$msysFna3d'; " +
    "cd '$msysStage'; " +
    "rm -rf build *.elf *.nro *.nacp *.lst *.map; " +
    "make -j4"
& $bash -lc $command
if ($LASTEXITCODE -ne 0) {
    throw "Graphics probe build failed."
}

$stageNro = Join-Path $stage 'castleminerz-graphics-probe.nro'
if (-not (Test-Path -LiteralPath $stageNro -PathType Leaf)) {
    throw "Graphics probe did not produce an NRO."
}

$bytes = [IO.File]::ReadAllBytes($stageNro)
if ($bytes.Length -lt 0x14 -or [Text.Encoding]::ASCII.GetString($bytes, 0x10, 4) -ne 'NRO0') {
    throw "Graphics probe output is not a valid NRO container."
}

$outputNro = Join-Path $repo 'castleminerz-graphics-probe.nro'
Copy-Item -LiteralPath $stageNro -Destination $outputNro -Force
Write-Host "Built $outputNro"
Write-Host "Size: $((Get-Item $outputNro).Length) bytes"
Write-Host "SHA-256: $((Get-FileHash $outputNro -Algorithm SHA256).Hash)"
