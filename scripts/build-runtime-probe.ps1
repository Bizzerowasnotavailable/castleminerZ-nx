# The project replaces mono-nx's sample AOT script with a pipeline that keeps
# FNA/compatibility assemblies, fails on AOT load errors, and starts from a clean
# RomFS assembly set. It is generated into the disposable staging directory.
$aotScript = @(
    '#!/bin/sh',
    'set -eu',
    '',
    'if ! which dotnet >/dev/null 2>&1; then',
    '    if [ -e ~/.dotnet/dotnet ]; then',
    '        export DOTNET_ROOT=~/.dotnet',
    '        export PATH=$PATH:$DOTNET_ROOT',
    '    else',
    '        echo "dotnet was not found"',
    '        exit 1',
    '    fi',
    'fi',
    '',
    'rm -rf output',
    '',
    'echo "Building the managed project..."',
    'dotnet build managed/program.csproj',
    '',
    'echo "Trimming the assemblies..."',
    'ILLINK=$MONO_NX_ROOT/artifacts/bin/Mono.Linker/Debug/net9.0/illink.dll',
    'ILLINK_CFG=$MONO_NX_ROOT/src/mono/System.Private.CoreLib/src/ILLink/ILLink.Descriptors.xml',
    'ILLINK_CFG1=$MONO_NX_ROOT/src/mono/System.Private.CoreLib/src/ILLink/ILLink.LinkAttributes.xml',
    '',
    'LIB_ROOT=$MONO_NX_ROOT/artifacts/bin/mono/libnx.arm64.Debug/',
    'FRAMEWORK_ROOT=$MONO_NX_ROOT/artifacts/bin/runtime/net9.0-libnx-Debug-arm64/',
    '',
    'dotnet $ILLINK -x $ILLINK_CFG -x $ILLINK_CFG1 \',
    '    --feature System.Resources.UseSystemResourceKeys true \',
    '    -d $LIB_ROOT -d $FRAMEWORK_ROOT -d managed/bin/Debug/net9.0 \',
    '    --trim-mode link -a managed/bin/Debug/net9.0/program.dll',
    '',
    'if [ ! -f output/FNA.dll ] || [ ! -f output/CastleMinerZ.XnaCompat.dll ]; then',
    '    echo "ILLink did not keep FNA.dll and CastleMinerZ.XnaCompat.dll." >&2',
    '    echo "Check the -d managed/bin/Debug/net9.0 argument." >&2',
    '    exit 1',
    'fi',
    '',
    'echo "Mono AOT build..."',
    'MONO_COMPILER=$MONO_NX_ROOT/artifacts/bin/mono/linux.x64.Debug/cross/linux-x64/libnx-arm64/mono-aot-cross',
    'export PATH=$PATH:$DEVKITPRO/devkitA64/bin/',
    '',
    'echo "build log" > mono_aot.log',
    'for file in output/*.dll; do',
    '    if ! "$MONO_COMPILER" --path=output/ --aot=full,static,direct-icalls,direct-pinvoke,tool-prefix=aarch64-none-elf- "$file" >> mono_aot.log 2>&1; then',
    '        echo "AOT failed for $file" >&2',
    '        exit 1',
    '    fi',
    'done',
    '',
    'if grep -q "Failed to load" mono_aot.log; then',
    '    echo "AOT reported assembly or method load failures:" >&2',
    '    grep "Failed to load" mono_aot.log >&2',
    '    exit 1',
    'fi',
    '',
    'echo "Copying outputs..."',
    'rm -f romfs/*.dll',
    'cp output/*.dll romfs/',
    'cp $ICU_NX_INSTALL_DIR/share/icu/77.1/icudt77l.dat romfs/',
    'grep -r "Linking symbol:" mono_aot.log | sed "s/Linking symbol: ''\([^'']*\)''\./STATIC_MONO_SYM(\1);/" > source/mono_symbols.h'
)
[IO.File]::WriteAllText(
